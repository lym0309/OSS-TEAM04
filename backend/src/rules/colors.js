// 응답의 clrNm을 색 계열로 묶어 서버에서 거른다. 매칭 점수의 "비슷한 계열" 판정에도 재사용한다.

// "블랙(검정)" → "검정", "기타" → "기타"
export function colorBaseName(clrNm = '') {
  const inner = clrNm.match(/\(([^)]+)\)/)
  return (inner ? inner[1] : clrNm).trim()
}

